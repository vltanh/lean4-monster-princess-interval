"use strict";
// Exact separation only. Every returned upper is accompanied by a complete
// integer flow and cut replay, including independent physical/calendar checks.
const fs=require("node:fs"),crypto=require("node:crypto"),readline=require("node:readline");
const S=require("../interval_sparse_upper/sparse_certificate.cjs");
const {maximumFlow}=require("../interval_clock_grid/qout_primal_certificate.cjs");
const {fraction}=require("../interval_clock_grid/exact_certificate.cjs");
let model=null,modelHash=null;
function hash(bytes){return crypto.createHash("sha256").update(bytes).digest("hex");}
function alternativeOptimalCuts(g,f,count,seed){
 if(!count)return [];
 if(!Number.isSafeInteger(count)||count<0||count>64)throw Error("alternative cut budget");
 const N=g.nodes.length+2,forward=Array.from({length:N},()=>[]),back=Array.from({length:N},()=>[]);
 const values=new Array(g.arcs.length).fill(0n);for(const [i,x] of f.entries)values[i]=BigInt(x);
 function edge(a,b){forward[a].push(b);back[b].push(a);}
 for(let i=0;i<g.arcs.length;i++){const [a,b,cap]=g.arcs[i],x=values[i];if(cap>x)edge(a,b);if(x>0n)edge(b,a);}
 const bad=new Uint8Array(N),queue=[g.T];bad[g.T]=1;
 for(let h=0;h<queue.length;h++)for(const x of back[queue[h]])if(!bad[x]){bad[x]=1;queue.push(x);}
 const minimal=new Uint8Array(N);for(const x of f.source_side)minimal[x]=1;
 const free=[];for(let i=0;i<g.nodes.length;i++)if(!bad[i]&&!minimal[i])free.push(i);
 const candidates=[Array.from({length:N},(_,i)=>i).filter(i=>!bad[i])];
 let state=(Number(seed)>>>0)||0x9e3779b9;
 function next(){state^=state<<13;state^=state>>>17;state^=state<<5;return state>>>0;}
 for(let q=1;q<count&&free.length;q++){
  const reached=minimal.slice(),todo=[];
  const picks=Math.min(free.length,Math.max(1,Math.floor(free.length*Math.pow(2,-1-(q%12)))));
  for(let j=0;j<picks;j++){const x=free[next()%free.length];if(!reached[x]){reached[x]=1;todo.push(x);}}
  for(let h=0;h<todo.length;h++)for(const x of forward[todo[h]])if(!reached[x]){reached[x]=1;todo.push(x);}
  if(reached[g.T])throw Error("residual closed set reached sink");
  candidates.push(Array.from({length:N},(_,i)=>i).filter(i=>reached[i]));
 }
 return candidates.map(ids=>{
  const side=new Set(ids);let cut=0n;for(const [a,b,c] of g.arcs)if(side.has(a)&&!side.has(b))cut+=c;
  if(cut!==f.flow)throw Error("alternative cut is not exactly optimal");
  return ids.filter(i=>i<g.nodes.length);
 });
}
async function run(){
 const input=readline.createInterface({input:process.stdin,crlfDelay:Infinity});
 for await(const line of input){
  try{
   const request=JSON.parse(line);
   if(request.command==="stop"){console.log(JSON.stringify({status:"STOPPED"}));break;}
   if(request.command==="load"){
    const bytes=fs.readFileSync(request.path);model=JSON.parse(bytes);modelHash=hash(bytes);
    console.log(JSON.stringify({status:"LOADED",model_sha256:modelHash,n:model.n,
      calendars:model.columns.length,event_nodes:model.qout_nodes.length,order_edges:model.qout_order.length}));continue;
   }
   if(!model)throw Error("no loaded model");
   const W=BigInt(request.denominator),weights=request.weights.map(BigInt);
   if(weights.length!==model.columns.length||W<=0n||weights.some(w=>w<0n)||weights.reduce((a,b)=>a+b,0n)!==W)throw Error("invalid rational probability vector");
   const paths=[];for(let i=0;i<weights.length;i++)if(weights[i]>0n)
    paths.push({...model.columns[i].plan,weight_numerator:String(weights[i])});
   const certificate={format:"sparse-qout-physical-upper-v1",
    scope:"Exact unrestricted physical Monster upper. Generated by cut/mixture discovery; no finite-response-bank lower claim.",
    n:model.n,pair_law:"fair_reflection",center_deadline:2,completion_horizon:8,
    physical_step:"1/"+(2*model.n),weight_denominator:String(W),paths,
    qout_nodes:model.qout_nodes,qout_order:model.qout_order,
    discovery_model_sha256:modelHash,discovery_request_sha256:hash(line)};
   const began=Date.now(),g=S.buildClosure(certificate),f=maximumFlow(g);
   certificate.closure_flow=f.entries;certificate.closure_source_side=f.source_side;
   certificate.global_upper=fraction(g.stats.mass+g.positive-f.flow,4n*BigInt(g.n)*g.W);
   const replay=S.verify(certificate);
   const alternatives=alternativeOptimalCuts(g,f,request.alternative_cuts||0,request.seed||0);
   if(request.prefix){
    fs.writeFileSync(request.prefix+".sparse.json",JSON.stringify(certificate)+"\n");
    fs.writeFileSync(request.prefix+".replay.json",JSON.stringify(replay,null,2)+"\n");
   }
   console.log(JSON.stringify({...replay,source_side:f.source_side.filter(i=>i<g.nodes.length),alternative_source_sides:alternatives,
      model_sha256:modelHash,seconds:(Date.now()-began)/1000}));
  }catch(error){console.log(JSON.stringify({status:"ERROR",error:String(error.stack)}));}
 }
}
run().catch(error=>{console.error(error.stack);process.exitCode=1;});
