#!/usr/bin/env python3
"""Analytic scalar oracle for separated early and late M2 turn sheets.

Variables are w0, then fixed-bin heights f, g, k, ell. Here k is the
TOTAL negative-start alpha density, including negative M1. The residual
negative-M2 line density is h0=k-ell-Hearly-Hlate. The early sheet is
generated by upward jumps of k at turn thresholds >=s0; its starts are
restricted to [left,right], with right<=s0. The zero-edge variant uses
k flat on [left,s0). The edge_trace variant permits general monotone k
and adds the explicit lower-edge density [k(s0)-k(z)]/(s0+6-z).

All features are integrated analytically. A numerical maximizer of the
four scalar parameters is discovery only; it is not an exact upper
certificate. The response reduction itself is analytic.
"""

import numpy as np
from numba import njit


@njit
def value_at(x, knots, values):
    for j in range(len(values)):
        if x < knots[j+1]-1e-13:
            return values[j]
    return values[-1]


@njit
def bin_at(x, knots):
    for j in range(len(knots)-1):
        if x < knots[j+1]-1e-13:
            return j
    return len(knots)-2


@njit
def i0(A, lo, hi):
    if hi <= lo:
        return 0.0
    return np.log((A-lo)/(A-hi))


@njit
def i1(A, lo, hi):
    if hi <= lo:
        return 0.0
    return A*i0(A,lo,hi)-(hi-lo)


@njit
def affine_integral(lo, hi, intercept, slope):
    if hi <= lo:
        return 0.0
    return intercept*(hi-lo)+slope*(hi*hi-lo*lo)/2


@njit
def beta(a, z, knots, kvals, left, right, s0, edge_trace=False):
    upper=min(a,right)
    if upper<=left or z<=s0:
        return 0.0
    result=0.0
    if edge_trace:
        ks=value_at(s0,knots,kvals)
        for j in range(len(kvals)):
            lo=max(left,knots[j]);hi=min(upper,knots[j+1])
            if hi>lo:result+=(ks-kvals[j])*i0(s0+6,lo,hi)
    for j in range(1,len(kvals)):
        turn=knots[j]
        active=turn>s0+1e-13 if edge_trace else turn>=s0-1e-13
        if active and turn<z-1e-13:
            result+=(kvals[j]-kvals[j-1])*i0(turn+6,left,upper)
    return result


@njit
def positive_prefix(parameters, knots, kvals, left, right, s0, edge_trace=False):
    """Return affine inverse segments (Vlo,Vhi,slope,intercept).

    For V<s0 use phi=max(u,V). For V>=s0 choose the first U where
    k(U)>=k(V)+beta_a(V), clipped to U>=max(u,V) and U<=1.
    On a step-k bin both k(V) and beta_a(V) are constant.
    """
    a,u,c,y=parameters
    segments=np.zeros((2*len(knots)+5,4))
    count=0
    if c<=0:
        return segments,count
    cuts=np.empty(2*len(knots)+6)
    ncut=0
    cuts[ncut]=0.0; ncut+=1
    cuts[ncut]=c; ncut+=1
    if 0<u<c:
        cuts[ncut]=u; ncut+=1
    if 0<s0<c:
        cuts[ncut]=s0; ncut+=1
    for t in knots:
        if 0<t<c:
            cuts[ncut]=t; ncut+=1
    cuts=np.sort(cuts[:ncut])
    for j in range(len(cuts)-1):
        lo,hi=cuts[j],cuts[j+1]
        if hi<=lo+1e-14:
            continue
        mid=(lo+hi)/2
        lower=max(u,mid)
        optimum=lower
        if mid>=s0:
            target=value_at(mid,knots,kvals)+beta(a,mid,knots,kvals,left,right,s0,edge_trace)
            if value_at(lower,knots,kvals)<target-1e-11:
                optimum=1.0
                for k in range(len(kvals)):
                    if knots[k]>=lower-1e-13 and kvals[k]>=target-1e-11:
                        optimum=knots[k]
                        break
        if optimum<=mid+1e-12:
            segments[count]=np.array([lo,hi,1.0,0.0])
        else:
            segments[count]=np.array([lo,hi,0.0,optimum])
        count+=1
    return segments,count


@njit
def baseline_prefix(parameters, knots):
    """The legal old one-switch prefix, used to seed a row pool."""
    a,u,c,y=parameters
    segments=np.zeros((2*len(knots)+5,4))
    count=0
    if c>0:
        hi=min(u,c)
        if hi>0:
            segments[count]=np.array([0.0,hi,0.0,u]); count+=1
        if c>u:
            segments[count]=np.array([u,c,1.0,0.0]); count+=1
    return segments,count


@njit
def phi_integral(lo,hi,parameters,segments,count):
    """Integral of the full positive-threshold inverse phi(V)."""
    if hi<=lo:
        return 0.0
    a,u,c,y=parameters
    result=0.0
    for j in range(count):
        l=max(lo,segments[j,0]); r=min(hi,segments[j,1])
        result+=affine_integral(l,r,segments[j,3],segments[j,2])
    l=max(lo,max(c,0.0)); r=min(hi,max(y,0.0))
    if r>l:
        result+=r-l
    l=max(lo,max(y,0.0))
    result+=affine_integral(l,hi,2.0,1.0)
    return result


@njit
def tail_width_integral(lo,hi,slope,intercept,binlo,binhi):
    """Integral of length([phi(V),1] intersect one U density bin)."""
    if hi<=lo:
        return 0.0
    if slope==0:
        return (hi-lo)*max(0.0,binhi-max(binlo,intercept))
    # Curved equality-face approximations may have any nonnegative slope.
    x0=(binlo-intercept)/slope
    x1=(binhi-intercept)/slope
    left=min(hi,x0)
    result=max(0.0,left-lo)*(binhi-binlo)
    l=max(lo,x0); r=min(hi,x1)
    result+=affine_integral(l,r,binhi-intercept,-slope)
    return result


@njit
def late_component(A,Hcoef,Mcoef,lo,hi,a,c,y):
    """Four-payoff correction for H=Hcoef/(A-z), M=Mcoef/(A-z)."""
    result=2*Mcoef*i0(A,lo,min(hi,a))
    result+=2*Mcoef*i0(A,max(lo,max(y,0.0)),hi)
    l=max(lo,max(c,0.0)); r=min(hi,max(y,0.0))
    result+=Hcoef*(i1(A,l,r)-7*i0(A,l,r))
    return result


@njit
def features(parameters,segments,count,knots,profile,left,right,s0,edge_trace=False):
    """Return exact analytic expected-capture features for a FROZEN path.

    Prefix segments must remain frozen when the returned row enters an LP.
    Computing a new optimal prefix under changed k creates a new row.
    """
    a,u,c,y=parameters
    n=len(knots)-1
    result=np.zeros(1+4*n)
    result[0]=5+c
    # Positive M1 and M2, and negative-M1 versus negative-M2 difference.
    breaks=np.sort(np.array([a,-c,-y,max(c,0.0),max(y,0.0)]))
    for j in range(n):
        lo,hi=knots[j],knots[j+1]
        cuts=np.empty(8); nc=0
        cuts[nc]=lo; nc+=1
        for cut in breaks:
            if lo<cut<hi:
                cuts[nc]=cut; nc+=1
        cuts[nc]=hi; nc+=1
        cuts=np.sort(cuts[:nc])
        for idx in range(nc-1):
            l,r=cuts[idx],cuts[idx+1]
            if r<=l:
                continue
            x=(l+r)/2
            if x<a:
                if -x<=c:
                    fvalue=6-3*x+u
                elif -x<=y:
                    fvalue=7-3*x
                else:
                    fvalue=8-4*x
            else:
                fvalue=8-3*x+y
            if x<-c:
                gvalue=12.0
            elif x<a:
                gvalue=4+u-x
            else:
                gvalue=5+c
            evalue=(2+2*x) if x<a else 0.0
            if x>c:
                evalue+=(x-7) if x<=y else (2*x-6)
            result[1+j]+=(r-l)*fvalue
            result[1+n+j]+=(r-l)*gvalue
            result[1+3*n+j]+=(r-l)*evalue

        # k: unreflected negative-M2 line captures.
        for idx in range(count):
            l=max(lo,segments[idx,0]); r=min(hi,segments[idx,1])
            result[1+2*n+j]+=affine_integral(
                l,r,segments[idx,3],1+segments[idx,2])
        result[1+2*n+j]+=8*max(0.0,hi-max(lo,max(c,0.0)))
        # Reflected negative starts: 4 below a and z+V(U=z) above a.
        result[1+2*n+j]+=4*max(0.0,min(hi,a)-lo)
        l=max(lo,a)
        result[1+2*n+j]+=affine_integral(l,hi,-a,1.0)
        neg_length=max(0.0,a+min(c,0.0))
        result[1+2*n+j]+=neg_length*max(0.0,hi-max(lo,u))
        for idx in range(count):
            result[1+2*n+j]+=tail_width_integral(
                segments[idx,0],segments[idx,1],segments[idx,2],
                segments[idx,3],lo,hi)

    # Replace part of the negative-M2 line by the early sheet.
    if edge_trace:
        ksidx=bin_at(s0,knots)
        for j in range(n):
            lo=max(left,knots[j]);hi=min(right,knots[j+1])
            if hi<=lo:continue
            turn=s0;A=turn+6
            correction=max(0.0,u-turn)*max(0.0,min(hi,c)-lo)
            correction-=(1-turn)**2*i0(A,max(lo,c),hi)
            reflect_i=i0(A,lo,min(a,hi))
            turn_integral=affine_integral(turn,1.0,-4.0,1.0)
            turn_integral+=phi_integral(turn,1.0,parameters,segments,count)
            correction+=reflect_i*turn_integral
            result[1+2*n+ksidx]+=correction
            result[1+2*n+j]-=correction
    for j in range(1,n):
        turn=knots[j]
        active=turn>s0+1e-13 if edge_trace else turn>=s0-1e-13
        if not active:
            continue
        A=turn+6
        correction=max(0.0,u-turn)*max(0.0,min(right,c)-left)
        correction-=(1-turn)**2*i0(A,max(left,c),right)
        reflect_i=i0(A,left,min(a,right))
        turn_integral=affine_integral(turn,1.0,-4.0,1.0)
        turn_integral+=phi_integral(turn,1.0,parameters,segments,count)
        correction+=reflect_i*turn_integral
        result[1+2*n+j]+=correction
        result[1+2*n+j-1]-=correction

    # Replace another part of that line by the post-one equality sheet.
    for j in range(n):
        v=profile[j]
        if v<=1+1e-13:
            continue
        lo,hi=knots[j],knots[j+1]
        index=bin_at(2-v,knots)
        coefficient=late_component(v+6,v-1,(v-1)**2/2,lo,hi,a,c,y)
        result[1+index]+=coefficient
        result[1+3*n+j]-=coefficient
        for k in range(1,n):
            turn=2-knots[k]
            if turn<v-1e-13:
                coefficient=late_component(turn+6,turn-1,(turn-1)**2/2,
                                           lo,hi,a,c,y)
                result[1+k]+=coefficient
                result[k]-=coefficient
    return result/4


@njit
def optimal_features(parameters,knots,profile,variables,left,right,s0,edge_trace=False):
    n=len(knots)-1
    kvals=variables[1+2*n:1+3*n]
    seg,count=positive_prefix(parameters,knots,kvals,left,right,s0,edge_trace)
    return features(parameters,seg,count,knots,profile,left,right,s0,edge_trace)


@njit
def residual_row(z,bin_index,knots,profile,left,right,s0,edge_trace=False):
    """Linear feature vector whose dot product is h0(z)."""
    n=len(knots)-1
    row=np.zeros(1+4*n)
    row[1+2*n+bin_index]=1.0
    row[1+3*n+bin_index]=-1.0
    if knots[bin_index]>=left-1e-13 and knots[bin_index+1]<=right+1e-13:
        if edge_trace:
            ksidx=bin_at(s0,knots)
            coeff=(1-s0)/(s0+6-z)
            row[1+2*n+ksidx]-=coeff
            row[1+2*n+bin_index]+=coeff
        for j in range(1,n):
            turn=knots[j]
            active=turn>s0+1e-13 if edge_trace else turn>=s0-1e-13
            if active:
                coeff=(1-turn)/(turn+6-z)
                row[1+2*n+j]-=coeff
                row[1+2*n+j-1]+=coeff
    v=profile[bin_index]
    if v>1+1e-13:
        fidx=bin_at(2-v,knots)
        coeff=(v-1)/(v+6-z)
        row[1+fidx]-=coeff
        row[1+3*n+bin_index]+=coeff
        for j in range(1,n):
            turn=2-knots[j]
            if turn<v-1e-13:
                coeff=(turn-1)/(turn+6-z)
                row[1+j]-=coeff
                row[j]+=coeff
    return row


def unit_to_parameters(r):
    a=float(r[0])
    u=a+(1-a)*float(r[1])
    c=-a+(1+a)*float(r[2])
    y=c+(1-c)*float(r[3])
    return np.array([a,u,c,y])


def parameters_to_unit(p):
    a,u,c,y=p
    return np.array([a,(u-a)/(1-a) if a<1 else 0,
                     (c+a)/(1+a),(y-c)/(1-c) if c<1 else 0])


def freeze_response(parameters,knots,profile,variables,left,right,s0,edge_trace=False):
    n=len(knots)-1
    seg,count=positive_prefix(np.asarray(parameters),knots,
        variables[1+2*n:1+3*n],left,right,s0,edge_trace)
    row=features(np.asarray(parameters),seg,count,knots,profile,left,right,s0,edge_trace)
    return row,seg[:count].copy()

def validate_structure(knots,profile,left,right,s0):
    assert 0<=left<right<=s0<=1
    assert all(any(abs(x-t)<1e-12 for t in knots) for x in (left,right,s0))
    for j,v in enumerate(profile):
        assert 1<=v<=2
        if v>1:
            # Late starts may use a different band, but stay below the
            # early turn band so reflected beta_a vanishes there.
            assert knots[j+1]<=s0+1e-12


@njit
def polynomial_over_affine(A,B,lo,hi,p0,p1,p2):
    """Integral of (p0+p1*z+p2*z^2)/(A+B*z)."""
    if hi<=lo:return 0.0
    if abs(B)<1e-10:
        return (p0*(hi-lo)+p1*(hi*hi-lo*lo)/2+p2*(hi**3-lo**3)/3)/A
    J0=np.log((A+B*hi)/(A+B*lo))/B
    J1=(hi-lo)/B-A*J0/B
    J2=(hi*hi-lo*lo)/(2*B)-A*J1/B
    return p0*J0+p1*J1+p2*J2


@njit
def affine_late_base(v0,v1,lo,hi,a,c,y):
    # v(z)=v0+v1*z; 2M=(v-1)^2/(v+6-z), H=(v-1)/(v+6-z).
    A=v0+6;B=v1-1;C=v0-1;D=v1
    result=polynomial_over_affine(A,B,lo,min(hi,a),C*C,2*C*D,D*D)
    result+=polynomial_over_affine(A,B,max(lo,max(y,0.)),hi,C*C,2*C*D,D*D)
    l=max(lo,max(c,0.));r=min(hi,max(y,0.))
    result+=polynomial_over_affine(A,B,l,r,-7*C,C-7*D,D)
    return result


@njit
def features_affine(parameters,segments,count,knots,affine_profile,left,right,s0,edge_trace=False):
    """Analytic features for a genuinely affine upper turn boundary."""
    n=len(knots)-1
    result=features(parameters,segments,count,knots,np.ones(n),left,right,s0,edge_trace)
    a,u,c,y=parameters
    for j in range(n):
        v0,v1=affine_profile[j]
        lo,hi=knots[j],knots[j+1]
        if v0+v1*(lo+hi)/2<=1+1e-13:continue
        cuts=np.empty(n+2);nc=0
        cuts[nc]=lo;nc+=1
        if abs(v1)>1e-14:
            for k in range(1,n):
                z=(2-knots[k]-v0)/v1
                if lo<z<hi:
                    cuts[nc]=z;nc+=1
        cuts[nc]=hi;nc+=1
        cuts=np.sort(cuts[:nc])
        for idx in range(nc-1):
            l,r=cuts[idx],cuts[idx+1]
            vmid=v0+v1*(l+r)/2
            fidx=bin_at(2-vmid,knots)
            coeff=affine_late_base(v0,v1,l,r,a,c,y)
            result[1+fidx]+=coeff/4
            result[1+3*n+j]-=coeff/4
            for k in range(1,n):
                turn=2-knots[k]
                if turn<vmid-1e-13:
                    coeff=late_component(turn+6,turn-1,(turn-1)**2/2,
                                        l,r,a,c,y)
                    result[1+k]+=coeff/4
                    result[k]-=coeff/4
    return result


@njit
def residual_row_affine(z,bin_index,knots,affine_profile,left,right,s0,edge_trace=False):
    n=len(knots)-1
    row=residual_row(z,bin_index,knots,np.ones(n),left,right,s0,edge_trace)
    v=affine_profile[bin_index,0]+affine_profile[bin_index,1]*z
    if v>1+1e-13:
        fidx=bin_at(2-v,knots)
        coeff=(v-1)/(v+6-z)
        row[1+fidx]-=coeff;row[1+3*n+bin_index]+=coeff
        for j in range(1,n):
            turn=2-knots[j]
            if turn<v-1e-13:
                coeff=(turn-1)/(turn+6-z)
                row[1+j]-=coeff;row[j]+=coeff
    return row


@njit
def optimal_features_affine(parameters,knots,affine_profile,variables,left,right,s0,edge_trace=False):
    n=len(knots)-1
    kvals=variables[1+2*n:1+3*n]
    seg,count=positive_prefix(parameters,knots,kvals,left,right,s0,edge_trace)
    return features_affine(parameters,seg,count,knots,affine_profile,left,right,s0,edge_trace)


def freeze_response_affine(parameters,knots,affine_profile,variables,left,right,s0,edge_trace=False):
    n=len(knots)-1
    seg,count=positive_prefix(np.asarray(parameters),knots,
        variables[1+2*n:1+3*n],left,right,s0,edge_trace)
    row=features_affine(np.asarray(parameters),seg,count,knots,affine_profile,left,right,s0,edge_trace)
    return row,seg[:count].copy()
